function toolList(tools: ToolDef[]): string {
  if (tools.length === 0) {
    return 'Инструментов для шагов пока нет: сохранить рабочий навык нельзя.';
  }
  const lines = tools.map((tool) => `- ${tool.name} — ${tool.description}`);
  return ['Инструменты, доступные в шагах (в шагах можно использовать только их):', ...lines].join('\n');
}

function jsonExample(title: string, skill: Skill): string[] {
  return [title, '```json', JSON.stringify(skill, null, 2), '```'];
}

