export function memoryBlock(records: MemoryLine[]): string | undefined {
  if (records.length === 0) {
    return undefined;
  }
  const lines = records.map((record) => `- ${record.id}: ${record.text}`);
  return ['Что ты помнишь по теме:', ...lines].join('\n');
}
